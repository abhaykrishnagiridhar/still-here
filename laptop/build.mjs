// Turns each TypeScript file into the plain JavaScript the browser loads.
//
//   node build.mjs          write the .js next to every .ts
//   node build.mjs --check  fail if any .js is out of date (used by the tests)
//
// It uses Node's own type stripper, so nothing has to be installed. That removes the types but
// does not check them: for that, install TypeScript (npm install) and run `npm run typecheck`.
// Only the plain TypeScript the pages use is supported (no enums or namespaces).
import { readFileSync, writeFileSync, readdirSync, existsSync } from "node:fs";
import { stripTypeScriptTypes } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const check = process.argv.includes("--check");

const sources = readdirSync(here).filter((name) => name.endsWith(".ts") && !name.endsWith(".test.ts"));
let stale = 0;

for (const name of sources) {
  const code = readFileSync(join(here, name), "utf8");
  const header = `// Generated from ${name} by build.mjs. Do not edit this file: edit ${name} and run node build.mjs.\n`;
  const output = header + stripTypeScriptTypes(code, { mode: "strip" });
  const target = join(here, name.replace(/\.ts$/, ".js"));
  if (check) {
    if (!existsSync(target) || readFileSync(target, "utf8") !== output) {
      console.error(`${name.replace(/\.ts$/, ".js")} is out of date`);
      stale += 1;
    }
  } else {
    writeFileSync(target, output);
    console.log(`built ${name.replace(/\.ts$/, ".js")}`);
  }
}

if (check && stale > 0) process.exit(1);
